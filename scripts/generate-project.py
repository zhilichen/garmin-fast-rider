#!/usr/bin/env python3
"""Generate device build selections and pixel geometry from shared design inputs."""
import argparse,json,math,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def contents():
    config=json.loads((ROOT/'config/devices.json').read_text());design=json.loads((ROOT/'design/layout.json').read_text());files={}
    for key,p in config['profiles'].items():
        w,h=p['width'],p['height'];scale=w/246
        px=lambda n:math.floor(n*scale+0.5)
        banner=math.floor(h*design['banner_fraction']+0.5);middle_start,middle_end=design['middle_reference'];mt=px(middle_start)
        mid=lambda n:math.floor(mt+(n-middle_start)*(banner-mt)/(middle_end-middle_start)+0.5)
        v={'WIDTH':w,'HEIGHT':h,'SCALE':scale}
        v.update({k:px(n) for k,n in design['x'].items()});v.update({k:px(n) for k,n in design['top'].items()});v.update({k:mid(n) for k,n in design['middle'].items()})
        v.update({'BANNER_TOP':banner,'HEADER_BASELINE':banner+px(18),'HEADER_BOLT_TOP':banner+px(4),'PLOT_TOP':banner+px(23),'PLOT_BOTTOM':h-px(3)})
        v['LEFT_WIDTH']=v['LEFT_RIGHT']-v['LEFT_EDGE'];v['RIGHT_WIDTH']=v['RIGHT_EDGE']-v['RIGHT_START'];v['RIGHT_TAP_LEFT']=v['COLUMN_DIVIDER']+v['STROKE'];v['PLOT_FILL_WIDTH']=v['PLOT_RIGHT']-v['PLOT_LEFT']+px(1)
        if p.get('emphasize_numbers',False):
            v['STATS_VALUE_WIDTH']=v['RIGHT_WIDTH']-px(2)
        s='// Generated by scripts/generate-project.py. Edit design/layout.json.\nimport Toybox.Math;\nmodule Layout {\n'
        s+=''.join(f'    const {k} = {n};\n' for k,n in v.items())
        s+='    function u(n) { return Math.round(n*SCALE).toNumber(); }\n}\n'
        files[f'config/display/{key}/Layout.mc']=s
        summary=design['summary']
        summary_banner=math.floor(h*summary['banner_fraction']+0.5)
        body=lambda n:math.floor(px(48)+(n-48)*(summary_banner-px(48))/198+0.5)
        stop={k:px(n) for k,n in summary['top'].items()}
        stop.update({k:body(n) for k,n in summary['body'].items()})
        stop['BANNER_TOP']=summary_banner
        stop['HEADER_BASELINE']=summary_banner+px(summary['header_baseline'])
        stop['HEADER_BOLT_TOP']=stop['HEADER_BASELINE']-px(14)
        stop['PLOT_TOP']=summary_banner+px(summary['plot_offset'])
        files[f'config/display/{key}/SummaryLayout.mc']='// Generated by scripts/generate-project.py. Edit design/layout.json.\nmodule SummaryLayout {\n'+''.join(f'    const {k} = {n};\n' for k,n in stop.items())+'}\n'
    svg=(ROOT/'design/launcher.svg').read_text()
    for size in sorted({d['icon_size'] for d in config['devices'].values()}):
        files[f'resources/icons/{size}/drawables.xml']='<drawables><bitmap id="LauncherIcon" filename="icon.svg"/></drawables>\n'
        files[f'resources/icons/{size}/icon.svg']=re.sub(r'(width|height)="35"',lambda m:m[1]+'="'+str(size)+'"',svg)
    for mode in ['live','demo','hardware','test']:

        source='source/app;source/model;source/ui;config/'+('demo' if mode=='test' else mode)
        if mode=='test':source+=';tests/monkeyc/common'
        s='# Generated by scripts/generate-project.py. Edit config/devices.json.\nproject.manifest = manifest.xml\nbase.sourcePath = '+source+'\nbase.resourcePath = resources/common\n'
        for device,p in config['devices'].items():
            input='touch' if p['touch'] else 'buttons'
            paths=f'$(base.sourcePath);source/input/{input};config/display/{p["profile"]}'
            if mode=='test':
                paths+=';tests/monkeyc/'+('legacy' if p['legacy_api'] else 'modern')
                if p['touch']:paths+=';tests/monkeyc/touch'
            s+=f'{device}.sourcePath = {paths}\n{device}.resourcePath = $(base.resourcePath);resources/fonts/{p["profile"]};resources/icons/{p["icon_size"]}\n'
        files['monkey.jungle' if mode=='live' else mode+'.jungle']=s
    # Keep manifest as a small hand-readable document; generated targets are checked.
    p=ROOT/'manifest.xml';s=p.read_text();start=s.index('    <iq:products>');end=s.index('</iq:products>',start)+len('</iq:products>')
    targets='    <iq:products>\n'+''.join(f'      <iq:product id="{d}"/>\n' for d in config['devices'])+'    </iq:products>'
    s=s[:start]+targets+s[end:];s=re.sub(r'minApiLevel="[^"]+"','minApiLevel="'+config['minimum_api']+'"',s);files['manifest.xml']=s
    tasks={"version":"2.0.0","tasks":[{"label":"FastRider: build","type":"shell","command":"./scripts/build.sh live ${input:device}","group":{"kind":"build","isDefault":True},"problemMatcher":[]},{"label":"FastRider: demo","type":"shell","command":"./scripts/run.sh demo ${input:device}","problemMatcher":[]},{"label":"FastRider: test","type":"shell","command":"./scripts/run.sh test ${input:device}","group":"test","problemMatcher":[]}],"inputs":[{"id":"device","type":"pickString","description":"Target Edge","options":list(config['devices']),"default":"edge840"}]}
    files['.vscode/tasks.json']=json.dumps(tasks,indent=2)+'\n'
    return files

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();bad=[]
    for name,text in contents().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text:bad.append(name)
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if bad:raise SystemExit('Outdated generated files: '+', '.join(bad))
