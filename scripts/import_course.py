#!/usr/bin/env python3
"""Compile a GPX elevation profile into bounded Monkey C course data (stdlib only)."""
import argparse
import bisect
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def haversine(a, b):
    lat1, lat2 = math.radians(a[0]), math.radians(b[0])
    dlat, dlon = lat2-lat1, math.radians(b[1]-a[1])
    h = math.sin(dlat/2)**2 + math.cos(lat1)*math.cos(lat2)*math.sin(dlon/2)**2
    return 6371000*2*math.asin(math.sqrt(min(1, h)))


def read_gpx(path):
    root = ET.parse(path).getroot()
    # Never join disjoint track segments silently; that invents course geometry.
    segments = root.findall('.//{*}trkseg')
    if len(segments) > 1:
        raise ValueError('GPX has multiple track segments; export one continuous track first')
    if not segments and len(root.findall('.//{*}rte')) > 1:
        raise ValueError('GPX has multiple routes; export one continuous route first')
    nodes = root.findall('.//{*}trkpt') or root.findall('.//{*}rtept')
    points = []
    for node in nodes:
        ele = node.find('{*}ele')
        if ele is None or ele.text is None:
            raise ValueError('Every track point needs elevation; use a GPX with elevation data')
        point = (float(node.attrib['lat']), float(node.attrib['lon']), float(ele.text))
        if not all(math.isfinite(x) for x in point) or not (-90 <= point[0] <= 90 and -180 <= point[1] <= 180):
            raise ValueError('Invalid GPX coordinate/elevation')
        if not points or haversine(points[-1], point) > 0.1:
            points.append(point)
    if len(points) < 2:
        raise ValueError('Need at least two distinct points')
    name_node = root.find('.//{*}trk/{*}name')
    if name_node is None:
        name_node = root.find('.//{*}rte/{*}name')
    return (name_node.text if name_node is not None else path.stem), points


def sample(points, count=160):
    distances = [0.0]
    for a, b in zip(points, points[1:]):
        distances.append(distances[-1]+haversine(a, b))
    length = distances[-1]
    if length < 1:
        raise ValueError('Course is shorter than one meter')
    # Fixed memory ceiling and uniform distance spacing, including both endpoints.
    out = []
    for i in range(min(count, len(points))):
        d = length*i/(min(count, len(points))-1)
        j = max(1, min(len(points)-1, bisect.bisect_left(distances, d)))
        t = (d-distances[j-1])/(distances[j]-distances[j-1])
        out.append((d, *(a+t*(b-a) for a, b in zip(points[j-1], points[j]))))
    ascent = sum(max(0, b[2]-a[2]) for a, b in zip(points, points[1:]))
    return out, ascent


def compile_course(path, output):
    name, points = read_gpx(path)
    is_sample = ET.parse(path).getroot().attrib.get('creator') == 'Summit synthetic demo'
    rows, ascent = sample(points)
    elevations = [round(r[3]) for r in rows]
    body = ['// Generated by scripts/import_course.py; do not edit.', 'module CourseData {',
            f'    const NAME = {json.dumps(name, ensure_ascii=True)};',
            f'    const IS_SAMPLE = {str(is_sample).lower()};',
            f'    const LENGTH = {rows[-1][0]:.3f};', f'    const ASCENT = {round(ascent)};',
            f'    const LOW = {min(elevations)};', f'    const HIGH = {max(elevations)};',
            '    var DISTANCES as Toybox.Lang.Array<Toybox.Lang.Float> = ['+', '.join(f'{r[0]:.3f}' for r in rows)+'];',
            '    var ELEVATIONS as Toybox.Lang.Array<Toybox.Lang.Number> = ['+', '.join(map(str, elevations))+'];',
            '    var POINTS as Toybox.Lang.Array<Toybox.Lang.Array<Toybox.Lang.Float>> = ['+', '.join(f'[{r[1]:.6f}, {r[2]:.6f}]' for r in rows)+'];', '}']
    output.write_text('\n'.join(body)+'\n')
    print(f'{name}: {rows[-1][0]/1000:.2f} km, +{ascent:.0f} m, {len(rows)} profile points → {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('gpx', type=Path)
    parser.add_argument('--output', type=Path, default=ROOT/'source/CourseData.mc')
    args = parser.parse_args()
    try:
        compile_course(args.gpx, args.output)
    except (ValueError, ET.ParseError) as error:
        parser.exit(2, f'Invalid course: {error}\n')
